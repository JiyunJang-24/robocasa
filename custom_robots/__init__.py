"""robosuite robot wrappers for arms that only ship as raw mujoco_menagerie MJCF.

mujoco_menagerie models are standalone MuJoCo scenes, not robosuite robots:
they bake in their own (equality-coupled) fingers, drive every joint with a
position/PD actuator, and have no `right_hand` body for robosuite to merge a
gripper onto. `scripts/convert_menagerie.py`-style preprocessing (see
custom_robots/<name>/robot.xml, generated by the converter kept alongside this
package) strips the fingers, swaps in torque `<motor>` actuators and adds the
mount body; these classes supply the Python half robosuite needs on top.

Importing this module registers both the bare arms and their OmronMobileBase
composites, mirroring robocasa_x's own compositional_robots.py.
"""

from pathlib import Path

import numpy as np

from robosuite.models.robots.manipulators.manipulator_model import ManipulatorModel
from robosuite.robots import register_robot_class

_ASSETS = Path(__file__).resolve().parent

# Menagerie's own `home` keyframe, restricted to the arm joints. Only a
# sane, non-singular starting point -- the kitchen-ready pose each robot
# actually gets seeded with at t=0 lives in KITCHEN_INIT_QPOS in
# generate_visual_robust_cross_embodiment_x.py.
_PIPER_HOME = np.array([0.0, 1.57, -1.3485, 0.0, 0.0, 0.0])
_YAM_HOME = np.array([0.0, 1.047, 1.047, 0.0, 0.0, 0.0])


class _MenagerieArm(ManipulatorModel):
    """Shared robosuite plumbing for the converted menagerie arms."""

    arms = ["right"]
    _xml = None
    _home = None

    def __init__(self, idn=0):
        super().__init__(str(_ASSETS / self._xml), idn=idn)

    @property
    def default_base(self):
        return "RethinkMount"

    @property
    def default_gripper(self):
        # Robotiq85 is the only gripper every other embodiment in this
        # pipeline has already been rendered with, so it keeps a new arm
        # comparable to them by default.
        return {"right": "Robotiq85Gripper"}

    @property
    def default_controller_config(self):
        # No per-robot JSON ships for these; the generation script hands a
        # full composite config in explicitly (see target_controller_config),
        # and UR5e's is the closest single-arm template for anything that
        # does fall back to this.
        return {"right": "default_ur5e"}

    @property
    def init_qpos(self):
        return self._home

    @property
    def base_xpos_offset(self):
        return {
            "bins": (-0.5, -0.1, 0),
            "empty": (-0.6, 0, 0),
            "table": lambda table_length: (-0.16 - table_length / 2, 0, 0),
        }

    @property
    def top_offset(self):
        return np.array((0, 0, 1.0))

    @property
    def _horizontal_radius(self):
        # Both arms are notably shorter-reach than UR5e/Panda (PiPER ~0.5m,
        # YAM ~0.55m fully extended), but this only gates placement checks.
        return 0.5

    @property
    def arm_type(self):
        return "single"


class PiPER(_MenagerieArm):
    """AgileX PiPER, 6-DOF."""

    _xml = "piper/robot.xml"
    _home = _PIPER_HOME


class YAM(_MenagerieArm):
    """I2RT YAM (Yet Another Manipulator), 6-DOF."""

    _xml = "yam/robot.xml"
    _home = _YAM_HOME


def _omron_base_xpos_offset():
    # Identical to robocasa_x's IIWAOmron/JacoOmron so a new arm lands in the
    # same place relative to the kitchen fixtures as the existing ones.
    return {
        "bins": (-0.6, -0.1, 0),
        "empty": (-0.6, 0, 0),
        "table": lambda table_length: (-0.16 - table_length / 2, 0, 0),
    }


@register_robot_class("WheeledRobot")
class PiPEROmron(PiPER):
    """PiPER on an Omron mobile base."""

    @property
    def default_base(self):
        return "OmronMobileBase"

    @property
    def default_arms(self):
        return {"right": "PiPER"}

    @property
    def base_xpos_offset(self):
        return _omron_base_xpos_offset()


@register_robot_class("WheeledRobot")
class YAMOmron(YAM):
    """YAM on an Omron mobile base."""

    @property
    def default_base(self):
        return "OmronMobileBase"

    @property
    def default_arms(self):
        return {"right": "YAM"}

    @property
    def base_xpos_offset(self):
        return _omron_base_xpos_offset()
